import { test } from 'node:test';
import assert   from 'node:assert/strict';
import fs       from 'node:fs';
import os       from 'node:os';
import path     from 'node:path';

import { isUsable } from '../../src/data/datasets.js';
import { GENERATOR_VERSION } from '../../src/data/generator.js';
import { datasetFile } from '../../src/core/paths.js';
import { columnSetOf, getColumns } from '../../src/utils/columns.js';
import { scenarios } from '../../src/config/scenarios.js';

function fixture(manifestContent) {
    const dir      = fs.mkdtempSync(path.join(os.tmpdir(), 'gridbench-dataset-'));
    const file     = path.join(dir, '10000.json');
    const manifest = path.join(dir, '10000.meta.json');
    fs.writeFileSync(file, '[]');
    if (manifestContent !== undefined) fs.writeFileSync(manifest, JSON.stringify(manifestContent));
    return { file, manifest };
}

const FIELDS = ['id', 'team', 'status'];

test('a dataset matching its manifest is served from disk', () => {
    const { file, manifest } = fixture({ generator: GENERATOR_VERSION, fields: FIELDS });
    assert.equal(isUsable(file, manifest, FIELDS), true);
});

test('a dataset generated by another version is regenerated', () => {
    const { file, manifest } = fixture({ generator: GENERATOR_VERSION + 1, fields: FIELDS });
    assert.equal(isUsable(file, manifest, FIELDS), false);
});

test('a dataset holding different fields than the scenario now reads is regenerated', () => {
    const { file, manifest } = fixture({ generator: GENERATOR_VERSION, fields: FIELDS });
    assert.equal(isUsable(file, manifest, [...FIELDS, 'city']), false);
    assert.equal(isUsable(file, manifest, ['status', 'team', 'id']), false, 'field order matters too');
});

test('a dataset with no manifest cannot say what produced it and is regenerated', () => {
    const { file, manifest } = fixture(undefined);
    assert.equal(isUsable(file, manifest, FIELDS), false);
});

test('a manifest without its dataset is not enough', () => {
    const { file, manifest } = fixture({ generator: GENERATOR_VERSION, fields: FIELDS });
    fs.unlinkSync(file);
    assert.equal(isUsable(file, manifest, FIELDS), false);
});

// ── One file per column set, not per scenario ────────────────────────────────

test('scenarios sharing a column set share one dataset file', () => {
    const sharing = ['tpl40', 'pln40', 'frz40'];
    const paths   = new Set(sharing.map(id => datasetFile(columnSetOf(scenarios[id]), 800_000)));

    assert.equal(paths.size, 1, `${sharing.join(', ')} should resolve to one file, got ${[...paths]}`);

    const fields = sharing.map(id => getColumns(scenarios[id]).map(column => column.id).join());
    assert.equal(new Set(fields).size, 1, 'they only share a file because they read the same columns');
});

test('scenarios reading different columns keep separate files', () => {
    const distinct = ['tpl10', 'tpl20', 'tpl40', 'tpl100'];
    const paths    = distinct.map(id => datasetFile(columnSetOf(scenarios[id]), 10_000));

    assert.equal(new Set(paths).size, distinct.length, 'a wider scenario must not read a narrower file');
});

test('a scenario without columnSet lands on the base set', () => {
    assert.equal(columnSetOf(scenarios.tpl10), 'base');
    assert.equal(columnSetOf(scenarios.frz10), 'base');
    assert.equal(columnSetOf(scenarios.tpl40), 'mix40');
});
